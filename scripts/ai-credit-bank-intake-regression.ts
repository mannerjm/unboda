// Cryptographic primitive smoke test without accessing real keys, card rails or customers.
const key=randomBytes(32),iv=randomBytes(12),aad=Buffer.from("synthetic-refund-id");
const plaintext=Buffer.from('{"accountNumber":"1234567890","accountHolder":"테스트"}');
const cipher=createCipheriv("aes-256-gcm",key,iv);cipher.setAAD(aad);
const ct=Buffer.concat([cipher.update(plaintext),cipher.final()]),tag=cipher.getAuthTag();
const decipher=createDecipheriv("aes-256-gcm",key,iv);decipher.setAAD(aad);decipher.setAuthTag(tag);
assert.equal(Buffer.concat([decipher.update(ct),decipher.final()]).toString(),plaintext.toString());
const tampered=createDecipheriv("aes-256-gcm",key,iv);tampered.setAAD(Buffer.from("wrong-id"));tampered.setAuthTag(tag);
assert.throws(()=>Buffer.concat([tampered.update(ct),tampered.final()]),"ciphertext must be bound to refund id");
